import { createRequire } from 'node:module';
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import http from 'node:http';
import { fileURLToPath } from 'node:url';
import { startFakeBackend } from './fake-backend.mjs';

const root = execSync('npm root -g').toString().trim();
const require = createRequire(path.join(root, 'x.js'));
const { chromium } = require('playwright');
const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = process.env.OUT || fs.mkdtempSync('/tmp/gcp-');
const WEB = path.join(OUT, 'web'); fs.mkdirSync(WEB, { recursive: true });

const errors = []; let fails = 0, promptAnswer = 'ok';
const ok = (c, msg) => { console.log((c ? '  ✓ ' : '  ✗ ') + msg); if (!c) fails++; };
const watch = (p, tag) => {
  p.on('pageerror', e => errors.push(tag + ' pageerror: ' + e.message));
  p.on('console', m => { if (m.type() === 'error' && !/fonts\.g|ERR_|Failed to load resource|status of 4\d\d/.test(m.text())) errors.push(tag + ' console: ' + m.text()); });
  p.on('dialog', d => d.accept(d.type() === 'prompt' ? promptAnswer : undefined));
};

const be = await startFakeBackend();
fs.writeFileSync(path.join(OUT, 'config.js'), `window.GC_CONFIG={supabaseUrl:${JSON.stringify(be.url)},supabaseKey:'sb_publishable_teste',brand:{name:'Menu Azul',logo:''}};`);
execSync('node build-web.mjs', { cwd: path.resolve(here, '..'), env: { ...process.env, WEB_OUT: WEB, CONFIG_FILE: path.join(OUT, 'config.js') } });
const web = http.createServer((req, res) => {   // imita o Cloudflare Pages com _redirects (SPA)
  const p = decodeURIComponent(req.url.split('?')[0]);
  const f = path.join(WEB, p === '/config.js' ? 'config.js' : 'index.html');
  res.setHeader('Content-Type', f.endsWith('.js') ? 'text/javascript' : 'text/html; charset=utf-8'); res.end(fs.readFileSync(f));
});
await new Promise(r => web.listen(0, '127.0.0.1', r));
const BASE = 'http://127.0.0.1:' + web.address().port;

await be.criarUsuarioAuth('dono@menuazul.com', 'senha-do-dono', true);
await be.criarUsuarioAuth('intruso@x.com', 'abc', false);
